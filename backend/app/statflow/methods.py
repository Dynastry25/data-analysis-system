#: Descriptive methods state this instead of a real list, so they are not given
#: an assumptions stage: there is nothing for the reader to go and check.
NO_ASSUMPTIONS = "hakuna assumption rasmi"


def _real_assumptions(method: Dict[str, Any]) -> List[str]:
    """The method's assumptions, ignoring the 'no formal assumptions' note."""
    return [
        item
        for item in method.get("assumptions", ())
        if str(item).strip().lower() != NO_ASSUMPTIONS
    ]


def _effective_extras(method: Dict[str, Any]) -> List[str]:
    """Extras actually used to build the plan, with assumptions derived.

    ``_m`` does not force every row that declares assumptions to list the
    ``assumptions`` extra, so the derivation lives here and both the signature
    and the plan must agree or the shared-plan cache would return the wrong
    steps.
    """
    extras = list(method.get("extras", ()))
    if _real_assumptions(method) and "assumptions" not in extras:
        extras.insert(0, "assumptions")
    return [extra for extra in extras if extra in STAGE_TEMPLATES]


def stage_signature(method: Dict[str, Any]) -> str:
    """Identity of a stage plan: same extras + same variables == same steps."""
    extras = "|".join(_effective_extras(method))
    requires = "|".join(method.get("requires", ()))
    return f"{extras}::{requires}"


def stage_plan(method: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Ordered stages for one method.

    Base stages (lengo -> data -> vigezo) come first, then the method's own
    extra stages, then the shared tail (mipangilio -> endesha -> matokeo ->
    tafsiri). Order numbers are reassigned here so the plan is always dense.
    """
    keys: List[str] = list(BASE_STAGE_ORDER)
    keys.extend(_effective_extras(method))
    keys.extend(TAIL_STAGE_ORDER)

    stages: List[Dict[str, Any]] = []
    for index, key in enumerate(keys, start=1):
        template = STAGE_TEMPLATES[key]
        stage: Dict[str, Any] = {
            "key": key,
            "order": index,
            "label": template["label"],
            "label_en": template["label_en"],
            "kind": template["kind"],
            "icon": template["icon"],
            "description": template["description"],
            "fields": list(template["fields"]),
            "gate": bool(template["gate"]),
        }
        if key == "vigezo":
            stage["fields"] = list(method.get("requires", ()))
        if key == "assumptions":
            stage["checks"] = _real_assumptions(method)
        if key == "endesha":
            stage["outputs"] = method.get("outputs", "")
        if key == "tafsiri":
            stage["outputs"] = method.get("outputs", "")
            stage["alternatives"] = list(method.get("alternatives", ()))
        stages.append(stage)
    return stages


def method(key: str) -> Optional[Dict[str, Any]]:
    """One catalogue row, stage plan included."""
    found = METHODS_BY_KEY.get(str(key))
    if found is None:
        return None
    return {**found, "stage_plan": stage_signature(found), "stages": stage_plan(found)}


def methods_for_category(category: str) -> List[Dict[str, Any]]:
    return [row for row in METHODS if row["category"] == str(category)]


def implemented_methods() -> List[Dict[str, Any]]:
    return [row for row in METHODS if row["implemented"]]


def engine_keys() -> List[str]:
    """The analysis_type values stats_engine actually implements."""
    return sorted({row["engine"] for row in METHODS if row["engine"]})


def method_catalog(include_stages: bool = True) -> Dict[str, Any]:
    """The whole guide as API data: categories, methods, stage plans, tables.

    ``stage_plans`` is keyed by ``stage_signature`` so a hundred methods do not
    duplicate the same twelve steps a hundred times.
    """
    plans: Dict[str, List[Dict[str, Any]]] = {}
    rows: List[Dict[str, Any]] = []
    for row in METHODS:
        signature = stage_signature(row)
        if include_stages and signature not in plans:
            plans[signature] = stage_plan(row)
        rows.append({**row, "stage_plan": signature})

    by_category: Dict[str, int] = {key: 0 for key in CATEGORY_KEYS}
    implemented_by_category: Dict[str, int] = {key: 0 for key in CATEGORY_KEYS}
    for row in METHODS:
        by_category[row["category"]] = by_category.get(row["category"], 0) + 1
        if row["implemented"]:
            implemented_by_category[row["category"]] = (
                implemented_by_category.get(row["category"], 0) + 1
            )

