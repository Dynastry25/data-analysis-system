def _m(
    key: str,
    label: str,
    label_sw: str,
    category: str,
    purpose: str,
    dv: str,
    assumptions: Sequence[str],
    outputs: str,
    *,
    requires: Sequence[str] = (),
    extras: Sequence[str] = (),
    engine: Optional[str] = None,
    alternatives: Sequence[str] = (),
    design: str = "cross-section",
    family: str = "",
    notes: str = "",
) -> Dict[str, Any]:
    """One catalogue row. ``engine`` set == stats_engine can actually run it.

    The guide asks for four things about every method: when to use it, which
    variables it suits, its assumptions and its outputs. ``when_to_use`` and
    ``variables`` are derived here so the studio does not have to reconstruct
    them from ``purpose`` and ``requires`` at render time.
    """
    rows = [str(item) for item in requires]
    return {
        "key": key,
        "label": label,
        "label_en": label,
        "label_sw": label_sw,
        "category": category,
        "family": family or category,
        "purpose": purpose,
        "when_to_use": purpose,
        "dv": dv,
        "variables": rows,
        "design": design,
        "assumptions": [str(item) for item in assumptions],
        "outputs": outputs,
        "alternatives": [str(item) for item in alternatives],
        "requires": rows,
        "extras": [str(item) for item in extras],
        "engine": engine,
        "implemented": engine is not None,
        "notes": notes,
    }


