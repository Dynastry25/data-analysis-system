"""Mwongozo wa Methods of Analysis — as machine-readable data.

Every method the platform knows about, taken from the analysis guide
(Sehemu A/B/C): lini kuitumia, variables zinazofaa, assumptions, outputs, na
kwa nini uichague. The module is deliberately *data first*: the studio UI,
the API catalogue and the recommendation engine read the same table, so a
method is never described one way in the picker and another way in the
checklist.

Two things live here:

1. ``CATEGORIES`` — the analysis groups shown beside the studio (Descriptive,
   Comparison, Association, Regression, ...).
2. ``METHODS`` — one entry per method. An entry with ``engine`` set is
   *implemented*: ``stats_engine`` has a handler with that analysis_type and
   the studio can run it. An entry without ``engine`` is reference material:
   the studio shows it, explains its assumptions/outputs and the stages it
   needs, but the run button stays disabled rather than pretending.

Stages are generated, never hand-written per method: the guide's three
selection questions (goal, DV type, data design) plus the checklist become the
same ordered pipeline, and the method's own nature adds the middle stages
(assumption checks, stationarity, survey weights, identification, tuning,
priors, codebook, inputs/outputs, items, effect sizes). ``method_catalog()``
therefore publishes a handful of distinct stage plans rather than one copy per
method.
"""

